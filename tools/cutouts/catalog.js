// Dumps the site's own vocabulary and movement tree to library/catalog.json,
// so the cutout pipeline reads the same words and families the site uses.
// Usage: node tools/cutouts/catalog.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..', '..');
const ctx = { window: { PCP: {} }, Math, console };
ctx.window.window = ctx.window;
vm.createContext(ctx);
for (const f of ['board.js', 'styles.js']) vm.runInContext(fs.readFileSync(path.join(root, 'site', 'src', f), 'utf8'), ctx, { filename: f });
const PCP = ctx.window.PCP, B = PCP.board, S = PCP.styles;
const out = {
  note: 'Generated by tools/cutouts/catalog.js from site/src/board.js and styles.js. Do not edit by hand.',
  vocabulary: Object.keys(B.TAGS),
  aliases: B.ALIASES,
  petals: B.PETALS.map(p => ({ key: p.key, ring: p.ring })),
  dyads: B.DYADS,
  movements: S.ALL.map(m => ({ id: m.id, name: m.name, branch: m.branch, branchName: m.branchName, emo: m.emo, layout: m.layout, motion: m.motion, colors: m.colors, blurb: m.blurb })),
  fallbacks: 'halftone torn wedge arrow target burst bars ember crow eye stamp scribble gear loaf'.split(' '),
  categories: ['food', 'object', 'memory', 'institution', 'concept', 'absurdity']
};
fs.writeFileSync(path.join(root, 'library', 'catalog.json'), JSON.stringify(out, null, 1) + '\n');
console.log('vocabulary', out.vocabulary.length, '| movements', out.movements.length);
